// Compact, read-only digest of the audit trail for external tools.
//
// The audit shards stay where the engine reads and writes them. This tool reads
// those shards through the engine's own reader (readAllAuditShards), so copies
// and merge order match what the engine sees, and writes one short Markdown file
// per intent plus an index under `aidlc/digest/<space>/`. The output is
// deterministic: it carries no "generated at" time and is rebuilt from the
// shards every run, so a diff shows only what changed in the work.
//
// Usage: bun aidlc-digest.ts [--project-dir <dir>] [--space <name>]

import { join, relative } from "node:path";
import { mkdirSync } from "node:fs";
import { listIntents } from "./aidlc-record-core.ts";
import { readAllAuditShards, resolveProjectDir } from "./aidlc-lib.ts";
import { activeSpace, workspaceRoot, writeBufferAtomic } from "./aidlc-locks.ts";

// Long values are cut so the timeline stays readable; the full text stays in the shard.
const VALUE_LIMIT = 160;

export interface DigestEvent {
  ts: string;
  event: string;
  fields: [string, string][];
}

// Shard blocks are `\n---\n`-separated; each field is one `**Key**: value` line
// (the engine escapes line breaks inside values). The first Timestamp and Event
// win, so older duplicated lines do not change the reading.
export function parseAuditText(text: string): DigestEvent[] {
  const events: (DigestEvent & { index: number })[] = [];
  for (const block of text.split("\n---\n")) {
    const fields: [string, string][] = [];
    for (const line of block.split("\n")) {
      const match = /^\*\*([^*]+)\*\*: ?(.*)$/.exec(line);
      if (match) fields.push([match[1], match[2]]);
    }
    const first = (name: string) => fields.find(([key]) => key === name)?.[1];
    const ts = first("Timestamp");
    const event = first("Event");
    if (!ts || !event) continue;
    events.push({
      ts,
      event,
      fields: fields.filter(([key]) => key !== "Timestamp" && key !== "Event"),
      index: events.length,
    });
  }
  events.sort((a, b) => (a.ts < b.ts ? -1 : a.ts > b.ts ? 1 : a.index - b.index));
  return events.map(({ index: _index, ...event }) => event);
}

const get = (event: DigestEvent, name: string): string | undefined =>
  event.fields.find(([key]) => key === name)?.[1];

const clip = (value: string): string =>
  value.length > VALUE_LIMIT ? `${value.slice(0, VALUE_LIMIT - 1)}…` : value;

// Latest stage status from the stage's own lifecycle events.
const STAGE_STATUS: Record<string, string> = {
  STAGE_STARTED: "started",
  STAGE_AWAITING_APPROVAL: "awaiting approval",
  STAGE_REVISING: "revising",
  STAGE_COMPLETED: "completed",
  STAGE_SKIPPED: "skipped",
  STAGE_JUMPED: "jumped to",
};

// Person decisions and lifecycle moments worth a line in the decisions list.
const DECISION_EVENTS = new Set([
  "GATE_APPROVED",
  "GATE_REJECTED",
  "PLAN_APPROVAL_RECORDED",
  "PLAN_APPROVAL_OVERRIDDEN",
  "STAGE_JUMPED",
  "STAGE_SKIPPED",
  "SCOPE_CHANGED",
  "WORKFLOW_COMPLETED",
  "WORKFLOW_PARKED",
  "WORKFLOW_ARCHIVED",
]);

const ARTIFACT_EVENTS = new Set(["ARTIFACT_CREATED", "ARTIFACT_UPDATED"]);

export function renderIntentDigest(
  events: DigestEvent[],
  meta: { slug: string; dirName: string; space: string; status: string; scope?: string; active: boolean },
): string {
  const out: string[] = [];
  out.push(`# ${meta.slug}`);
  out.push("");
  out.push(
    `- Record: \`aidlc/spaces/${meta.space}/intents/${meta.dirName}/\` (shards in \`audit/\`)`,
    `- Status: ${meta.status}${meta.active ? " (active)" : ""}${meta.scope ? `, scope ${meta.scope}` : ""}`,
    `- Events: ${events.length}`,
  );
  if (events.length > 0) {
    out.push(`- First: ${events[0].ts}`, `- Last: ${events[events.length - 1].ts} ${events[events.length - 1].event}`);
  }
  out.push("", "> Generated by `aidlc-digest`. Do not edit; regenerate from the audit shards.", "");

  // Stages: the latest lifecycle event per stage, in the order the stages first appear.
  const stageOrder: string[] = [];
  const stageLast = new Map<string, DigestEvent>();
  for (const event of events) {
    const stage = get(event, "Stage");
    if (!stage || !(event.event in STAGE_STATUS)) continue;
    if (!stageLast.has(stage)) stageOrder.push(stage);
    stageLast.set(stage, event);
  }
  out.push("## Stages", "");
  if (stageOrder.length === 0) out.push("None yet.");
  for (const stage of stageOrder) {
    const event = stageLast.get(stage) as DigestEvent;
    out.push(`- ${stage}: ${STAGE_STATUS[event.event]} (${event.ts})`);
  }
  out.push("");

  // Built: every artifact file the hooks recorded, with first and last write.
  const artifacts = new Map<string, { created: string; updated: string; writes: number }>();
  for (const event of events) {
    if (!ARTIFACT_EVENTS.has(event.event)) continue;
    const file = get(event, "File");
    if (!file) continue;
    const seen = artifacts.get(file);
    if (!seen) artifacts.set(file, { created: event.ts, updated: event.ts, writes: 1 });
    else {
      seen.updated = event.ts;
      seen.writes += 1;
    }
  }
  out.push("## Built", "");
  if (artifacts.size === 0) out.push("No artifacts recorded.");
  for (const [file, info] of artifacts) {
    out.push(`- ${file}: first ${info.created}, last ${info.updated}, ${info.writes} write${info.writes === 1 ? "" : "s"}`);
  }
  out.push("");

  // Decisions: what the person decided, in order.
  const decisions = events.filter((event) => DECISION_EVENTS.has(event.event));
  out.push("## Decisions", "");
  if (decisions.length === 0) out.push("None recorded.");
  for (const event of decisions) {
    const detail = ["Stage", "User Input", "Reason", "Feedback", "Details", "Scope", "Target", "Direction"]
      .map((name) => get(event, name) && `${name}=${clip(get(event, name) as string)}`)
      .filter(Boolean)
      .join(" ");
    out.push(`- ${event.ts} ${event.event}${detail ? ` ${detail}` : ""}`);
  }
  out.push("");

  // Timeline: one line per event, every field kept, long values cut.
  out.push("## Timeline", "");
  for (const event of events) {
    const fields = event.fields.map(([key, value]) => `${key}=${clip(value)}`).join(" ");
    out.push(`- ${event.ts} ${event.event}${fields ? ` ${fields}` : ""}`);
  }
  out.push("");
  return out.join("\n");
}

export function renderIndex(
  space: string,
  rows: { dirName: string; slug: string; status: string; events: number; last: string; active: boolean }[],
): string {
  const out = [`# Audit digest: space ${space}`, "", "> Generated by `aidlc-digest`. Do not edit; regenerate from the audit shards.", ""];
  if (rows.length === 0) out.push("No intents recorded.");
  for (const row of rows) {
    out.push(
      `- [${row.slug}](${row.dirName}.md): ${row.status}${row.active ? " (active)" : ""}, ${row.events} events, last ${row.last || "none"}`,
    );
  }
  out.push("");
  return out.join("\n");
}

export function buildDigest(projectDir: string, space?: string): { written: string[]; intents: number } {
  const sp = space ?? activeSpace(projectDir);
  const outDir = join(workspaceRoot(projectDir), "digest", sp);
  mkdirSync(outDir, { recursive: true });
  const written: string[] = [];
  const rows: Parameters<typeof renderIndex>[1] = [];
  const intents = listIntents(projectDir, sp);
  for (const intent of intents) {
    if (intent.dirName === null) continue;
    const events = parseAuditText(readAllAuditShards(projectDir, intent.dirName, sp));
    const body = renderIntentDigest(events, {
      slug: intent.slug,
      dirName: intent.dirName,
      space: sp,
      status: intent.status,
      scope: intent.scope,
      active: intent.active,
    });
    const file = join(outDir, `${intent.dirName}.md`);
    writeBufferAtomic(file, Buffer.from(body, "utf-8"));
    written.push(relative(projectDir, file));
    rows.push({
      dirName: intent.dirName,
      slug: intent.slug,
      status: intent.status,
      events: events.length,
      last: events.length > 0 ? events[events.length - 1].ts : "",
      active: intent.active,
    });
  }
  const index = join(outDir, "INDEX.md");
  writeBufferAtomic(index, Buffer.from(renderIndex(sp, rows), "utf-8"));
  written.push(relative(projectDir, index));
  return { written, intents: rows.length };
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const flag = (name: string) => {
    const at = args.indexOf(name);
    return at >= 0 ? args[at + 1] : undefined;
  };
  const projectDir = resolveProjectDir(flag("--project-dir"));
  const result = buildDigest(projectDir, flag("--space"));
  console.log(`Wrote ${result.written.length} file(s) for ${result.intents} intent(s):`);
  for (const path of result.written) console.log(`  ${path}`);
}
